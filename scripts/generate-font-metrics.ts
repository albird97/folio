/**
 * Regenerates packages/document-model/src/standard-font-metrics.ts.
 *
 *   pnpm font-metrics:generate
 *
 * Added text is written with the standard PDF fonts (Helvetica, Times-Roman,
 * Courier). The editor and the exporter both lay it out with these widths,
 * so line breaks on screen match the saved file. The widths come from the
 * Adobe Core 14 AFM files bundled with pdf-lib, which may be copied and
 * distributed for any purpose.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Encodings, Font, FontNames } from '@cantoo/pdf-lib/standard-fonts';

const OUT = join(
  import.meta.dirname,
  '..',
  'packages',
  'document-model',
  'src',
  'standard-font-metrics.ts',
);

const FAMILIES = {
  sans: FontNames.Helvetica,
  serif: FontNames.TimesRoman,
  mono: FontNames.Courier,
} as const;

const encoding = Encodings.WinAnsi;
const lines: string[] = [];
for (const [family, fontName] of Object.entries(FAMILIES)) {
  const font = Font.load(fontName);
  const pairs: number[] = [];
  for (const codePoint of [...encoding.supportedCodePoints].sort((a, b) => a - b)) {
    const glyph = encoding.encodeUnicodeCodePoint(codePoint);
    const width = font.getWidthOfGlyph(glyph.name);
    if (width === undefined) continue;
    pairs.push(codePoint, width);
  }
  lines.push(
    `  ${family}: {`,
    `    ascent: ${font.Ascender},`,
    `    descent: ${font.Descender},`,
    `    widths: [${pairs.join(', ')}],`,
    '  },',
  );
}

writeFileSync(
  OUT,
  [
    '// Generated by scripts/generate-font-metrics.ts from the Adobe Core 14 font',
    '// metrics bundled with pdf-lib. Do not edit.',
    '',
    '/**',
    ' * Per standard font: ascent and descent, and the advance width of every',
    ' * character it can show as [code point, width, …] pairs, all in 1/1000 em.',
    ' */',
    'export const STANDARD_FONT_METRICS = {',
    ...lines,
    '} as const;',
    '',
  ].join('\n'),
);
console.log(`Font metrics written to ${OUT}`);
